"""Build the bundled demo corpus in corpus/samples/ + ground truth in corpus/metadata.csv.

Produces files that exercise every branch of the four-state provenance routing:

  VALID_AI_ASSERTED  peachcheck-ad-*.jpg — fictional campaign-ad mockups rendered
                     here with PIL, then signed with a real C2PA manifest carrying
                     digitalSourceType=trainedAlgorithmicMedia (the file "confesses"
                     to being AI-generated by its own signed testimony). Signed with
                     the standard C2PA *test* certificate (scripts/test_certs/), so
                     validators report the signature as valid but the signer as not
                     on the production trust list — which the app reports honestly.
  UNTRUSTED          a credential-stripped re-save of a signed ad (the "laundering"
                     case) and an unsigned mockup carrying a Stable Diffusion-style
                     metadata tag (the "hard metadata contradiction" case).
  VALID / TAMPERED   covered by the official C2PA public test files downloaded by
                     this script (adobe-*, truepic-*: intact, bad-signature, and
                     hash-mismatch variants).

All candidates/committees named in the mockups are fictional.

Run:  .venv/bin/python scripts/make_demo_corpus.py
"""

from __future__ import annotations

import csv
import io
import os
import urllib.request

from PIL import Image, ImageDraw, ImageFont, PngImagePlugin

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAMPLES_DIR = os.path.join(BASE_DIR, "corpus", "samples")
CSV_PATH = os.path.join(BASE_DIR, "corpus", "metadata.csv")
CERT_DIR = os.path.join(BASE_DIR, "scripts", "test_certs")

PUBLIC_TESTFILES_BASE = (
    "https://raw.githubusercontent.com/c2pa-org/public-testfiles/main/legacy/1.4/image/jpeg"
)
PUBLIC_TESTFILES = {
    # filename -> (expected c2pa_state, notes)
    "adobe-20220124-C.jpg": ("valid_capture", "Official C2PA test file: intact signed manifest."),
    "adobe-20220124-CI.jpg": ("valid_capture", "Official C2PA test file: intact manifest with ingredient history."),
    "adobe-20220124-XCA.jpg": ("tampered", "Official C2PA test file: content edited after signing (hash mismatch)."),
    "adobe-20220124-E-dat-CA.jpg": ("tampered", "Official C2PA test file: assertion data altered after signing."),
    "adobe-20220124-E-sig-CA.jpg": ("untrusted", "Official C2PA test file: claim signature invalid."),
    "adobe-20220124-A.jpg": ("untrusted", "Official C2PA test file: no manifest embedded."),
    "truepic-20230212-camera.jpg": ("valid_capture", "Truepic-signed camera capture."),
    "truepic-20230212-landscape.jpg": ("valid_capture", "Truepic-signed camera capture."),
    "nikon-20221019-building.jpeg": ("untrusted", "Signed, but the signing certificate has expired."),
}

# Wrapped short so every line fits well inside the frame — OCR must see whole words.
DISCLOSURE_LINES = [
    "PAID FOR BY PEACHES FOR",
    "GEORGIA COMMITTEE. THIS",
    "AD WAS GENERATED WITH",
    "ARTIFICIAL INTELLIGENCE.",
    "DEPICTED EVENTS MAY NOT",
    "HAVE ACTUALLY OCCURRED.",
]


def _font(size: int) -> ImageFont.FreeTypeFont:
    # Pillow's bundled scalable default keeps this script portable across machines.
    return ImageFont.load_default(size=size)


def _draw_ad_body(draw: ImageDraw.ImageDraw, width: int, body_bottom: int) -> None:
    """The fictional ad itself: flat colors, big type — enough for OCR to find real
    'body text' to use as the contrast baseline."""
    draw.rectangle((0, 0, width, body_bottom), fill=(30, 41, 59))
    draw.text((60, 90), "GEORGIA DESERVES BETTER", font=_font(72), fill=(255, 255, 255))
    draw.text((60, 200), "RE-ELECT SENATOR J. PEACH", font=_font(52), fill=(251, 191, 36))
    draw.text((60, 290), "VOTE NOVEMBER 3", font=_font(44), fill=(226, 232, 240))


def make_ad_compliant(path: str) -> None:
    """Disclosure block fills the bottom ~42% of the frame, black on white — passes
    the 30% height bar, the contrast safe harbor, and all three content checks."""
    width, height = 1080, 1350  # 4:5 social-ad format
    img = Image.new("RGB", (width, height), (255, 255, 255))
    draw = ImageDraw.Draw(img)
    band_top = int(height * 0.48)
    _draw_ad_body(draw, width, band_top)
    y = band_top + 52
    for line in DISCLOSURE_LINES:
        draw.text((50, y), line, font=_font(56), fill=(0, 0, 0))
        y += 108
    img.save(path, "JPEG", quality=92)


def make_ad_tiny_disclosure(path: str) -> None:
    """Disclosure exists but is a single small, low-contrast line — passes the
    content checks, fails the 30% height bar and likely the contrast bar."""
    width, height = 1080, 1350
    img = Image.new("RGB", (width, height), (255, 255, 255))
    draw = ImageDraw.Draw(img)
    _draw_ad_body(draw, width, int(height * 0.92))
    draw.text(
        (28, height - 46),
        "Paid for by Peaches for GA Committee. Generated with AI. "
        "Events may not have actually occurred.",
        font=_font(20),
        fill=(178, 178, 178),
    )
    img.save(path, "JPEG", quality=92)


def make_ad_no_disclosure(path: str) -> None:
    """No disclosure at all, unsigned, but carrying a Stable Diffusion-style PNG text
    tag — the 'hard metadata contradiction' the forensic panel can catch."""
    width, height = 1080, 1350
    img = Image.new("RGB", (width, height), (255, 255, 255))
    draw = ImageDraw.Draw(img)
    _draw_ad_body(draw, width, height)
    meta = PngImagePlugin.PngInfo()
    # Mirrors how Stable Diffusion WebUI actually writes its generation settings.
    meta.add_text("parameters", "campaign ad, senator, photorealistic. Model: Stable Diffusion XL")
    img.save(path, "PNG", pnginfo=meta)


def sign_with_ai_assertion(source_path: str, dest_path: str, title: str) -> None:
    """Embed + sign a C2PA manifest declaring the file AI-generated.

    Uses the standard C2PA test certificate (checked into scripts/test_certs/, same
    fixtures the c2pa-rs SDK tests use). A production deployment would use a real
    signing credential; for the demo the *mechanism* — signed manifest, verified
    signature, AI assertion routed to measurement — is identical.
    """
    import c2pa

    with open(os.path.join(CERT_DIR, "es256_certs.pem"), "rb") as f:
        certs = f.read()
    with open(os.path.join(CERT_DIR, "es256_private.key"), "rb") as f:
        key = f.read()

    manifest = """
    {
      "claim_generator_info": [{"name": "PeachCheck Demo Generator", "version": "0.2.0"}],
      "title": "%s",
      "assertions": [
        {
          "label": "c2pa.actions",
          "data": {
            "actions": [
              {
                "action": "c2pa.created",
                "digitalSourceType": "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"
              }
            ]
          }
        }
      ]
    }
    """ % title

    signer_info = c2pa.C2paSignerInfo(
        alg=b"es256", sign_cert=certs, private_key=key, ta_url=b"http://timestamp.digicert.com"
    )
    signer = c2pa.Signer.from_info(signer_info)
    builder = c2pa.Builder.from_json(manifest)
    if os.path.exists(dest_path):
        os.remove(dest_path)
    builder.sign_file(source_path, dest_path, signer)


def strip_credentials(source_path: str, dest_path: str) -> None:
    """Re-encode through raw pixels, dropping the manifest — exactly what messaging
    apps and screenshots do. The laundered copy should come back 'unknown provenance'
    while its perceptual hash still matches the signed original."""
    import numpy as np

    with Image.open(source_path) as img:
        clean = Image.fromarray(np.asarray(img.convert("RGB")))
    clean.save(dest_path, "JPEG", quality=88)


def download_public_testfiles() -> None:
    for name in PUBLIC_TESTFILES:
        dest = os.path.join(SAMPLES_DIR, name)
        if os.path.exists(dest):
            continue
        url = f"{PUBLIC_TESTFILES_BASE}/{name}"
        print(f"  downloading {name}")
        with urllib.request.urlopen(url) as resp, open(dest, "wb") as out:
            out.write(resp.read())


def main() -> None:
    os.makedirs(SAMPLES_DIR, exist_ok=True)
    rows: list[dict] = []

    print("Downloading official C2PA public test files…")
    download_public_testfiles()
    for name, (state, notes) in PUBLIC_TESTFILES.items():
        rows.append(
            {
                "filename": name,
                "source_url": f"{PUBLIC_TESTFILES_BASE}/{name}",
                "generator_or_camera": "c2pa-org test corpus",
                "c2pa_state": state,
                "ground_truth_label": "test_fixture",
                "laundering_applied": "none",
                "notes": notes,
            }
        )

    print("Rendering fictional campaign-ad mockups…")
    unsigned_compliant = os.path.join(SAMPLES_DIR, "_unsigned_compliant.jpg")
    unsigned_tiny = os.path.join(SAMPLES_DIR, "_unsigned_tiny.jpg")
    make_ad_compliant(unsigned_compliant)
    make_ad_tiny_disclosure(unsigned_tiny)
    make_ad_no_disclosure(os.path.join(SAMPLES_DIR, "peachcheck-ad-no-disclosure.png"))

    print("Signing mockups with AI-generation assertions…")
    signed_compliant = os.path.join(SAMPLES_DIR, "peachcheck-ad-compliant.jpg")
    signed_tiny = os.path.join(SAMPLES_DIR, "peachcheck-ad-tiny-disclosure.jpg")
    sign_with_ai_assertion(unsigned_compliant, signed_compliant, "peachcheck-ad-compliant.jpg")
    sign_with_ai_assertion(unsigned_tiny, signed_tiny, "peachcheck-ad-tiny-disclosure.jpg")
    os.remove(unsigned_compliant)
    os.remove(unsigned_tiny)

    print("Creating credential-stripped (laundered) copy…")
    strip_credentials(signed_compliant, os.path.join(SAMPLES_DIR, "peachcheck-ad-stripped.jpg"))

    rows += [
        {
            "filename": "peachcheck-ad-compliant.jpg",
            "source_url": "generated by scripts/make_demo_corpus.py",
            "generator_or_camera": "PIL mockup + c2pa test signer",
            "c2pa_state": "valid_ai_asserted",
            "ground_truth_label": "synthetic",
            "laundering_applied": "none",
            "notes": "Fictional ad; signed AI assertion; disclosure sized to pass every SB 9 bar.",
        },
        {
            "filename": "peachcheck-ad-tiny-disclosure.jpg",
            "source_url": "generated by scripts/make_demo_corpus.py",
            "generator_or_camera": "PIL mockup + c2pa test signer",
            "c2pa_state": "valid_ai_asserted",
            "ground_truth_label": "synthetic",
            "laundering_applied": "none",
            "notes": "Fictional ad; signed AI assertion; disclosure present but far below the 30% height bar.",
        },
        {
            "filename": "peachcheck-ad-no-disclosure.png",
            "source_url": "generated by scripts/make_demo_corpus.py",
            "generator_or_camera": "PIL mockup (Stable Diffusion-style metadata tag)",
            "c2pa_state": "untrusted",
            "ground_truth_label": "synthetic",
            "laundering_applied": "none",
            "notes": "Fictional ad; unsigned, no disclosure; carries an SD-style metadata tag the forensic panel flags.",
        },
        {
            "filename": "peachcheck-ad-stripped.jpg",
            "source_url": "generated by scripts/make_demo_corpus.py",
            "generator_or_camera": "PIL mockup, credentials stripped on re-encode",
            "c2pa_state": "untrusted",
            "ground_truth_label": "synthetic",
            "laundering_applied": "re-encode (manifest stripped)",
            "notes": "Laundered copy of the compliant ad — same picture, credentials gone; perceptual hash still matches.",
        },
    ]

    with open(CSV_PATH, "w", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "filename",
                "source_url",
                "generator_or_camera",
                "c2pa_state",
                "ground_truth_label",
                "laundering_applied",
                "notes",
            ],
        )
        writer.writeheader()
        writer.writerows(rows)

    print(f"Done: {len(rows)} corpus entries -> {CSV_PATH}")


if __name__ == "__main__":
    main()
